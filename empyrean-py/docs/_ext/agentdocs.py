def _fence_closer(opener):
    """Return a regex matching the closing line of a fence opened by ``opener``."""
    char = re.escape(opener[0])
    return re.compile(r"^\s*" + char + "{" + str(len(opener)) + r",}\s*$")


def _fenced_blocks(text, name):
    """Return the body text of every ```` ```{name} ... ``` ```` block in ``text``."""
    blocks = []
    lines = text.split("\n")
    i = 0
    n = len(lines)
    while i < n:
        match = re.match(r"^(\s*)(`{3,}|~{3,})\{" + re.escape(name) + r"\}\s*(.*)$", lines[i])
        if match:
            close = _fence_closer(match.group(2))
            j = i + 1
            body = []
            while j < n and not close.match(lines[j]):
                body.append(lines[j])
                j += 1
            blocks.append("\n".join(body))
            i = j + 1 if j < n else n
        else:
            i += 1
    return blocks


def _render_directive(name, arg, body, titles):
    """Render one fenced directive to a list of plain-Markdown lines."""
    if name == "toctree":
        return []
    if name == "eval-rst":
        joined = "\n".join(body)
        if "autosummary" in joined:
            return ["- `" + nm + "`" for nm in _API_NAME_RE.findall(joined)]
        return []
    if name == "admonition" or name in _ADMONITIONS:
        label = arg if (name == "admonition" and arg) else _ADMONITIONS.get(name, "Note")
        inner = strip_myst("\n".join(body), titles).split("\n")
        while inner and not inner[0].strip():
            inner.pop(0)
        while inner and not inner[-1].strip():
            inner.pop()
        quoted = ["> **" + label + ":**"]
        quoted += [">" if not ln.strip() else "> " + ln for ln in inner]
        return quoted
    if name == "math":
        inner = [ln for ln in body if not re.match(r"^\s*:[A-Za-z][\w-]*:", ln)]
        return ["$$", *inner, "$$"]
    # Unknown or content-bearing directive (e.g. glossary): keep the body,
    # minus any option lines, stripped recursively.
    kept = [ln for ln in body if not re.match(r"^\s*:[A-Za-z][\w-]*:", ln)]
    return strip_myst("\n".join(kept), titles).split("\n")


def _apply_roles(line, titles):
    """Replace inline cross-reference roles in a single line of text."""

    def role(match):
        """Render a cross-reference role to inline code of its qualified name."""
        target = match.group(1).strip()
        text, ref = _split_display(target)
        if text is not None:
            return "`" + text + "`"
        return "`" + ref.lstrip("~") + "`"

    def doc(match):
        """Render a {doc} role to the target page title, or the path in backticks."""
        target = match.group(1).strip()
        text, ref = _split_display(target)
        if text is not None:
            return text
        key = ref.lstrip("./")
        while key.startswith("../"):
            key = key[3:]
        if titles and key in titles:
            return titles[key]
        return "`" + ref + "`"

    def refterm(match):
        """Render a {ref}/{term} role to its visible text."""
        target = match.group(1).strip()
        text, ref = _split_display(target)
        return text if text is not None else ref

    line = _ROLE_RE.sub(role, line)
    line = _DOC_RE.sub(doc, line)
    line = _REFTERM_RE.sub(refterm, line)
    return line


def _split_display(target):
    """Split a ``"text <ref>"`` role target; return ``(text, ref)`` or ``(None, ref)``."""
    match = re.match(r"^(.*?)\s*<([^>]+)>$", target)
    if match:
        return match.group(1).strip(), match.group(2).strip()
    return None, target


def _render_entry(module, name):
    """Render one ``empyrean.X`` API entry to a single line, or ``None`` if unresolved."""
    parts = name.split(".")[1:]
    obj = module
    try:
        for part in parts:
            obj = getattr(obj, part)
    except AttributeError:
        return None
    short = parts[-1]
    if inspect.isclass(obj):
        methods = _public_methods(obj)
        doc = _first_doc_line(obj)
        if not methods:
            head = "`" + short + "`"
        elif len(methods) <= 8:
            head = "`" + short + "` (" + ", ".join(methods) + ")"
        else:
            head = "`" + short + "` (" + str(len(methods)) + " methods)"
        return head + (" — " + doc if doc else "")
    if inspect.isroutine(obj) or callable(obj):
        return _render_signature(short, obj)
    return "`" + short + "`"


def _render_signature(short, obj):
    """Render ``name(params)`` using parameter NAMES only (byte-stable)."""
    try:
        signature = inspect.signature(obj)
    except (TypeError, ValueError):
        return "`" + short + "`"
    parts = []
    star_done = False
    for param in signature.parameters.values():
        if param.name.startswith("_"):
            continue
        if param.kind is inspect.Parameter.VAR_POSITIONAL:
            parts.append("*" + param.name)
            star_done = True
            continue
        if param.kind is inspect.Parameter.VAR_KEYWORD:
            parts.append("**" + param.name)
            continue
        if param.kind is inspect.Parameter.KEYWORD_ONLY and not star_done:
            parts.append("*")
            star_done = True
        if param.default is inspect.Parameter.empty:
            parts.append(param.name)
        else:
            parts.append(param.name + "=…")
    return "`" + short + "(" + ", ".join(parts) + ")`"


def _public_methods(cls):
    """Return the class's own public method names (sorted), excluding inherited ones."""
    methods = []
    for name in sorted(vars(cls)):
        if name.startswith("_"):
            continue
        try:
            value = inspect.getattr_static(cls, name)
        except AttributeError:
            value = vars(cls)[name]
        if isinstance(value, (staticmethod, classmethod)):
            value = value.__func__
        if inspect.isroutine(value):
            methods.append(name)
    return methods


def _first_doc_line(obj):
    """Return the first non-empty line of ``obj``'s docstring (``""`` if none)."""
    for line in (inspect.getdoc(obj) or "").split("\n"):
        if line.strip():
            return line.strip()
    return ""


