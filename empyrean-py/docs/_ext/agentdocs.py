def _first_paragraph(text):
    """Return the first prose paragraph of ``text`` as one whitespace-joined line."""
    started = False
    paragraph = []
    for raw in text.split("\n"):
        line = raw.strip()
        if not started:
            if line.startswith("#") or _nonprose(line):
                continue
            started = True
            paragraph.append(line)
        else:
            if line == "" or _nonprose(line):
                break
            paragraph.append(line)
    return " ".join(paragraph)


def _nonprose(line):
    """Return ``True`` if ``line`` begins a non-prose block (fence, table, list, ...)."""
    if line == "":
        return True
    if line.startswith(("```", "~~~", ":::", "|", ">", "<!--", "- ", "* ", "#")):
        return True
    if re.match(r"^\d+\.\s", line):
        return True
    if re.match(r"^:[A-Za-z][\w-]*:", line):
        return True
    return bool(_LABEL_RE.match(line))


def _with_provenance(src_path, body):
    """Prefix ``body`` with the standard "do not edit" provenance comment."""
    comment = (
        "<!-- generated from empyrean-py/docs/" + src_path + " by agentdocs.py; do not edit -->"
    )
    return comment + "\n\n" + body.strip("\n") + "\n"


def _write_if_changed(path, content):
    """Write ``content`` to ``path`` only if the bytes differ; return whether written."""
    data = content.encode("utf-8")
    if path.exists() and path.read_bytes() == data:
        return False
    path.write_bytes(data)
    return True


def _head_api_refs(head):
    """Return the sorted set of ``empyrean.*`` dotted names backticked in ``head``."""
    refs = set()
    for span in re.findall(r"`([^`]+)`", head):
        refs.update(_DOTTED_RE.findall(span))
    return sorted(refs)


def _resolves(module, dotted):
    """Return ``True`` if the dotted ``empyrean.*`` name resolves by a getattr chain."""
    obj = module
    for part in dotted.split(".")[1:]:
        try:
            obj = getattr(obj, part)
        except AttributeError:
            return False
    return True


def _frontmatter_description(block):
    """Extract the quoted ``description`` scalar from a frontmatter ``block``."""
    for pattern in (r'^description:\s*"(.*)"\s*$', r"^description:\s*'(.*)'\s*$"):
        match = re.search(pattern, block, re.MULTILINE)
        if match:
            return match.group(1)
    return None


def _pyproject_project_fields(pyproject):
    """Return the string-valued keys of ``[project]`` in ``pyproject`` as a dict.

    A deliberately small reader: ``version`` and ``description`` are plain
    double-quoted strings on their own lines, and the package supports Python
    3.10, where ``tomllib`` does not exist.
    """
    fields = {}
    in_project = False
    for line in Path(pyproject).read_text("utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("["):
            in_project = stripped == "[project]"
            continue
        if not in_project:
            continue
        match = re.match(r'^([A-Za-z0-9_-]+)\s*=\s*"((?:[^"\\]|\\.)*)"\s*(?:#.*)?$', stripped)
        if match:
            fields[match.group(1)] = match.group(2)
    return fields


def _meta(docs_dir):
    """Return ``(version, description)`` from ``pyproject.toml``, else installed metadata.

    The tree's ``pyproject.toml`` is the source of truth, so the generated files
    are byte-stable for a given checkout whatever version happens to be
    installed in the environment that runs the build or the tests.
    """
    version = None
    description = None
    pyproject = Path(docs_dir).parent / "pyproject.toml"
    if pyproject.exists():
        fields = _pyproject_project_fields(pyproject)
        version = fields.get("version")
        description = fields.get("description")
    if version is None or description is None:
        import importlib.metadata as md

        try:
            version = version or md.version("empyrean")
            description = description or md.metadata("empyrean")["Summary"]
        except (md.PackageNotFoundError, KeyError):
            pass
    return version or "0.0.0", description or "empyrean"


def _on_build_finished(app, exception):
    """On a successful HTML build, write the llms files and regenerate the skill."""
    if exception is not None or app.builder.name != "html":
        return
    import importlib

    from sphinx.util import logging as sphinx_logging

    logger = sphinx_logging.getLogger(__name__)
    module = importlib.import_module("empyrean")
    srcdir = Path(str(app.srcdir))
    _, description = _meta(srcdir)
    base_url = app.config.agentdocs_base_url
    for path in write_llms(app.outdir, srcdir, module, base_url, app.config.release, description):
        logger.info("agentdocs: wrote %s", path)

    skill_dir_cfg = app.config.agentdocs_skill_dir
    if skill_dir_cfg:
        skill_dir = (srcdir / skill_dir_cfg).resolve()
        repo_root = skill_dir.parents[len(SKILL_SUBDIR) - 1]
        check_skill_head((skill_dir / "SKILL.md").read_text(encoding="utf-8"), module)
        for path in write_skill(repo_root, module):
            logger.info("agentdocs: wrote %s", path)


