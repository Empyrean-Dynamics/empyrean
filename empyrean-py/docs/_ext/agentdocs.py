"""Generate the agent-facing views of the empyrean docs from the Sphinx sources.

This module turns the MyST Markdown documentation into the forms a coding
agent reads: the generated region of ``plugins/empyrean/skills/empyrean/SKILL.md`` plus its
``references/*`` copies, and the ``llms.txt`` / ``llms-full.txt`` indexes
(https://llmstxt.org) with one plain-Markdown page per docname.

Everything here is a pure function over text and the imported ``empyrean``
module, so the heavy lifting is unit-testable without a Sphinx build. Sphinx
itself is imported only inside :func:`setup` and :func:`_on_build_finished`;
importing this module has no third-party dependency beyond the standard
library (and ``empyrean`` when an API index is actually rendered).

The API index doubles as a docs-vs-package drift check: every ``empyrean.X``
named in ``api.md`` must resolve on the installed package, or
:func:`api_index` raises :class:`LookupError` and the build fails loudly.
"""

from __future__ import annotations

import argparse
import inspect
import re
import sys
from pathlib import Path

SKILL_SUBDIR = ("plugins", "empyrean", "skills", "empyrean")
"""Path of the generated skill below the repository root: the plugin root is
``plugins/empyrean`` (the marketplace at the repository root points there), and
the skill folder sits under its ``skills/``."""


# The two marker lines bracket the generated region of SKILL.md. They are
# kept verbatim; only the text between them is rewritten.
START_MARKER = (
    "<!-- agentdocs:generated:start - regenerated by `make html` in "
    "empyrean-py/docs; do not edit below this line -->"
)
END_MARKER = "<!-- agentdocs:generated:end -->"

# api.md has no prose sentence, so its reference-file summary is fixed.
API_SUMMARY = (
    "Every public function and class, grouped, with the call signature or methods for each."
)

# Reference files embedded in the skill: (output basename, source docname).
# ``index`` is renamed to ``quickstart``; the ``agents`` page is excluded
# because it explains how to install the skill, which is pointless inside it.
_REFERENCE_PAGES = [
    ("quickstart.md", "index"),
    ("about.md", "about"),
    ("propagation.md", "cookbook/propagation"),
    ("impact-probability.md", "cookbook/impact-probability"),
    ("orbit-determination.md", "cookbook/orbit-determination"),
    ("sensitivity.md", "cookbook/sensitivity"),
    ("data-setup.md", "cookbook/data-setup"),
    ("frames-units.md", "reference/frames-units"),
    ("glossary.md", "reference/glossary"),
    ("validation.md", "reference/validation"),
]

# Admonition directive name -> blockquote label.
_ADMONITIONS = {
    "note": "Note",
    "warning": "Warning",
    "tip": "Tip",
    "important": "Important",
    "caution": "Caution",
    "danger": "Danger",
    "hint": "Hint",
    "attention": "Attention",
    "seealso": "See also",
    "error": "Error",
}

# Inline cross-reference roles that carry a dotted target.
_ROLE_RE = re.compile(r"[:{](?:func|class|attr|meth|mod|obj|data|exc)[:}]`([^`]+)`")
_DOC_RE = re.compile(r"[:{]doc[:}]`([^`]+)`")
_REFTERM_RE = re.compile(r"[:{](?:ref|term)[:}]`([^`]+)`")
_LABEL_RE = re.compile(r"^\([A-Za-z0-9_.-]+\)=\s*$")
_API_NAME_RE = re.compile(r"^\s+(empyrean\.[A-Za-z_][A-Za-z0-9_]*)\s*$", re.MULTILINE)
_DOTTED_RE = re.compile(r"\bempyrean\.[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*")


def page_order(docs_dir):
    """Return the docnames in reading order.

    ``index`` comes first, then every entry of every ``{toctree}`` block in
    ``index.md`` in the order they appear. Lines that configure the toctree
    (``:maxdepth:`` and friends) are skipped.
    """
    docs_dir = Path(docs_dir)
    text = (docs_dir / "index.md").read_text(encoding="utf-8")
    order = ["index"]
    for body in _fenced_blocks(text, "toctree"):
        for line in body.splitlines():
            entry = line.strip()
            if not entry or entry.startswith(":"):
                continue
            order.append(entry)
    return order


def page_title(text):
    """Return the text of the first ``# `` heading in ``text`` (``""`` if none)."""
    for line in text.split("\n"):
        match = re.match(r"^#\s+(.+?)\s*$", line)
        if match:
            return match.group(1).strip()
    return ""


def strip_myst(text, titles=None):
    """Convert MyST Markdown to plain Markdown, never raising on unknown constructs.

    Cross-reference roles (``{func}``/``{class}``/``{attr}``/``{meth}``/
    ``{mod}``/``{obj}``/``{data}``/``{exc}``, in both ``{role}`` and RST
    ``:role:`` spellings) become inline code of the qualified name with a
    leading ``~`` dropped; ``{doc}`` resolves to the target page's title via
    ``titles`` (or the path in backticks); ``{ref}``/``{term}`` become their
    text. ``{toctree}`` blocks are removed; ``{note}``/``{warning}``/``{tip}``/
    ``{important}``/``{admonition}`` become a blockquote led by ``**Label:**``;
    sphinx-design ``tab-set``/``grid`` fences are flattened (titled items to a
    bold line); ``{eval-rst}`` autosummary blocks become a bullet list of their
    ``empyrean.Name`` entries and other ``{eval-rst}`` blocks are dropped;
    ``(label)=`` targets are removed. ``$...$`` math and ordinary fenced code
    blocks are passed through untouched. Idempotent on plain Markdown.
    """
    lines = text.split("\n")
    out = []
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]

        # Ordinary code fence (```lang / ~~~), but not a ```{directive}.
        code = re.match(r"^(\s*)(`{3,}|~{3,})(.*)$", line)
        if code and not code.group(3).lstrip().startswith("{"):
            close = _fence_closer(code.group(2))
            out.append(line)
            i += 1
            while i < n:
                out.append(lines[i])
                if close.match(lines[i]):
                    i += 1
                    break
                i += 1
            continue

        # Fenced directive ```{name} args ... ```.
        directive = re.match(r"^(\s*)(`{3,}|~{3,})\{([a-zA-Z_-]+)\}\s*(.*)$", line)
        if directive:
            close = _fence_closer(directive.group(2))
            j = i + 1
            body = []
            while j < n and not close.match(lines[j]):
                body.append(lines[j])
                j += 1
            i = j + 1 if j < n else n
            out.extend(
                _render_directive(
                    directive.group(3).lower(), directive.group(4).strip(), body, titles
                )
            )
            continue

        # Colon-fence open (sphinx-design): :::{name} args.
        colon = re.match(r"^(:{3,})\{([a-zA-Z_-]+)\}\s*(.*)$", line)
        if colon:
            name = colon.group(2).lower()
            arg = colon.group(3).strip()
            if name in ("tab-item", "grid-item-card", "card", "dropdown") and arg:
                out.append("**" + _apply_roles(arg, titles) + "**")
            i += 1
            continue

        # Colon-fence close (bare colons) or MyST target label.
        if re.match(r"^:{3,}\s*$", line) or _LABEL_RE.match(line):
            i += 1
            continue

        out.append(_apply_roles(line, titles))
        i += 1

    return "\n".join(out)


def api_groups(api_md_text):
    """Return ``(header, [empyrean.Name, ...])`` for each ``##``/``###`` group.

    ``header`` keeps its ``##``/``###`` prefix. Names are collected from every
    ``{eval-rst}`` autosummary block under the header, in source order.
    """
    groups = []
    header = None
    names = []
    lines = api_md_text.split("\n")
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        head = re.match(r"^(#{2,3})\s+(.+?)\s*$", line)
        if head:
            if header is not None:
                groups.append((header, names))
            header = head.group(1) + " " + head.group(2).strip()
            names = []
            i += 1
            continue
        rst = re.match(r"^(\s*)(`{3,}|~{3,})\{eval-rst\}\s*$", line)
        if rst:
            close = _fence_closer(rst.group(2))
            j = i + 1
            while j < n and not close.match(lines[j]):
                entry = _API_NAME_RE.match(lines[j])
                if entry and header is not None:
                    names.append(entry.group(1))
                j += 1
            i = j + 1 if j < n else n
            continue
        i += 1
    if header is not None:
        groups.append((header, names))
    return groups


def api_index(api_md_text, module):
    """Render ``api.md`` as a plain-Markdown index, one line per entry.

    Every documented ``empyrean.X`` must resolve on ``module`` by a getattr
    chain; otherwise :class:`LookupError` is raised listing every unresolved
    name. This is the docs-vs-package drift check, and it fails loudly on
    purpose. The output is byte-stable: parameter and method NAMES only, never
    a repr of an annotation or a default value.
    """
    groups = api_groups(api_md_text)
    rendered = []
    unresolved = []
    for header, names in groups:
        entries = []
        for name in names:
            line = _render_entry(module, name)
            if line is None:
                unresolved.append(name)
            else:
                entries.append(line)
        rendered.append((header, entries))
    if unresolved:
        raise LookupError(
            "empyrean API drift: documented in api.md but unresolved on the "
            "package: " + ", ".join(unresolved)
        )
    return "\n\n".join("\n".join([header, *entries]) for header, entries in rendered)


def quick_reference(index_md_text):
    """Return the ``## Quick reference`` section of ``index.md``, role-stripped."""
    lines = index_md_text.split("\n")
    out = []
    collecting = False
    for line in lines:
        if re.match(r"^##\s+Quick reference\s*$", line):
            collecting = True
            out.append(line)
            continue
        if collecting:
            if re.match(r"^#{1,6}\s+", line) or re.match(r"^(\s*)(`{3,}|~{3,}|:{3,})", line):
                break
            out.append(line)
    return strip_myst("\n".join(out).rstrip())


def skill_tail(docs_dir, module):
    """Build the generated region of SKILL.md.

    In order: the documented version and how to compare it with the installed
    one, the quick-reference table, the ``Pipeline entry points`` and
    ``I/O helpers`` API groups inline, a pointer to ``references/api.md`` for
    the rest, and a ``Reference files`` list with a one-line summary per file.
    """
    docs_dir = Path(docs_dir)
    titles = _titles(docs_dir)
    version, _ = _meta(docs_dir)
    sections = [
        "This skill documents empyrean "
        + version
        + ". Check the installed version with "
        + "`python -c \"import importlib.metadata as m; print(m.version('empyrean'))\"` "
        + "and upgrade (`pip install -U empyrean`, with `--pre` when the documented "
        + "version is a release candidate) before relying on an API the installed "
        + "version lacks.",
        quick_reference((docs_dir / "index.md").read_text(encoding="utf-8")),
    ]

    groups = dict(api_groups((docs_dir / "api.md").read_text(encoding="utf-8")))
    for header in ("## Pipeline entry points", "## I/O helpers"):
        lines = [header]
        for name in groups.get(header, []):
            entry = _render_entry(module, name)
            if entry is not None:
                lines.append(entry)
        sections.append("\n".join(lines))
    sections.append("The rest of the public API is in `references/api.md`.")

    summaries = _reference_summaries(docs_dir, titles)
    ref_lines = ["## Reference files", ""]
    for out_name, _ in _REFERENCE_PAGES:
        ref_lines.append("- `references/" + out_name + "` — " + summaries[out_name])
    ref_lines.append("- `references/api.md` — " + API_SUMMARY)
    sections.append("\n".join(ref_lines))

    return "\n\n".join(sections)


def reference_files(docs_dir, titles, module=None):
    """Return ``{basename: content}`` for every reference file in the skill.

    ``index.md`` becomes ``quickstart.md``; the cookbook and reference pages
    flatten to their basenames; ``agents`` is excluded; ``api.md`` is the
    generated API index. Each value starts with a provenance comment. The
    ``module`` is needed only for ``api.md`` and defaults to ``empyrean``.
    """
    docs_dir = Path(docs_dir)
    files = {}
    for out_name, docname in _REFERENCE_PAGES:
        body = strip_myst((docs_dir / (docname + ".md")).read_text(encoding="utf-8"), titles)
        files[out_name] = _with_provenance(docname + ".md", body)
    if module is None:
        import importlib

        module = importlib.import_module("empyrean")
    api_body = api_index((docs_dir / "api.md").read_text(encoding="utf-8"), module)
    files["api.md"] = _with_provenance("api.md", api_body)
    return files


def write_skill(repo_root, module):
    """Rewrite SKILL.md's generated region and ``references/*``; return written paths.

    Marker lines are preserved verbatim with exactly one newline after the
    start marker and before the end marker. Stray files under ``references/``
    are deleted. A file is written only when its bytes actually change, so a
    no-op regeneration touches nothing.
    """
    repo_root = Path(repo_root)
    skill_dir = repo_root.joinpath(*SKILL_SUBDIR)
    docs_dir = repo_root / "empyrean-py" / "docs"
    written = []

    skill_path = skill_dir / "SKILL.md"
    original = skill_path.read_text(encoding="utf-8")
    start = original.index(START_MARKER) + len(START_MARKER)
    end = original.index(END_MARKER, start)
    tail = skill_tail(docs_dir, module).strip("\n")
    new_text = original[:start] + "\n" + tail + "\n" + original[end:]
    if _write_if_changed(skill_path, new_text):
        written.append(skill_path)

    ref_dir = skill_dir / "references"
    ref_dir.mkdir(parents=True, exist_ok=True)
    files = reference_files(docs_dir, _titles(docs_dir), module)
    for name, content in files.items():
        if _write_if_changed(ref_dir / name, content):
            written.append(ref_dir / name)
    for path in sorted(ref_dir.iterdir()):
        if path.is_file() and path.name not in files:
            path.unlink()
    return written


def check_skill_head(skill_text, module):
    """Validate the hand-written head of SKILL.md, raising on any problem.

    Every backticked ``empyrean.X`` / ``empyrean.X.Y`` mention before the start
    marker must resolve by a getattr chain; the frontmatter ``name`` must be
    ``empyrean``; and ``description`` must be at most 1024 characters. Failures
    are collected and reported together as a single :class:`ValueError`.
    """
    head = skill_text.split(START_MARKER)[0]
    problems = []

    front = re.match(r"^---\n(.*?)\n---\n", skill_text, re.DOTALL)
    if not front:
        problems.append("missing YAML frontmatter")
    else:
        block = front.group(1)
        name_match = re.search(r"^name:\s*(.+?)\s*$", block, re.MULTILINE)
        name = name_match.group(1).strip().strip("\"'") if name_match else None
        if name != "empyrean":
            problems.append(f"frontmatter `name` must be 'empyrean', got {name!r}")
        desc = _frontmatter_description(block)
        if desc is None:
            problems.append("frontmatter `description` missing or not a quoted scalar")
        elif len(desc) > 1024:
            problems.append(f"frontmatter `description` is {len(desc)} chars (limit 1024)")

    for ref in _head_api_refs(head):
        if not _resolves(module, ref):
            problems.append(f"unresolved API reference in head: `{ref}`")

    if problems:
        raise ValueError("SKILL.md head check failed:\n  - " + "\n  - ".join(problems))


def llms_index(pages, titles, summaries, base_url, version, description):
    """Build the ``llms.txt`` index (https://llmstxt.org) for the documentation."""
    base = base_url.rstrip("/")
    lines = [
        "# empyrean",
        "",
        "> "
        + _sentence(description)
        + " Install with `pip install empyrean`; this file indexes the "
        + "documentation of version "
        + str(version)
        + ".",
        "",
        "## Documentation",
        "",
    ]
    for docname in pages:
        title = titles.get(docname, docname)
        line = "- [" + title + "](" + base + "/" + docname + ".md)"
        summary = summaries.get(docname, "")
        if summary:
            line += ": " + summary
        lines.append(line)
    lines += [
        "",
        "## Verification",
        "",
        (
            "- [Validation report](https://validation.empyrean-dynamics.com/latest/"
            "validation_report.html): every release compared across its Python, "
            "Rust, C and CLI channels and against JPL Horizons and ASSIST"
        ),
        (
            "- [Scenarios](https://github.com/Empyrean-Dynamics/empyrean-scenarios): "
            "nine runnable walkthroughs (Python, Rust, notebooks) with "
            "reference-value tables"
        ),
        "",
        "## Optional",
        "",
        (
            "- [llms-full.txt](" + base + "/llms-full.txt): every documentation "
            "page concatenated into one file"
        ),
        (
            "- [Agent skill](https://github.com/Empyrean-Dynamics/empyrean/tree/main/"
            "plugins/empyrean/skills/empyrean): the SKILL.md generated from these pages"
        ),
        (
            "- [GitHub repository](https://github.com/Empyrean-Dynamics/empyrean): "
            "source, issues and releases"
        ),
        "- [PyPI](https://pypi.org/project/empyrean/): install with pip",
    ]
    return "\n".join(lines) + "\n"


def _sentence(text):
    """Return ``text`` stripped and closed with a period unless it already ends one."""
    text = text.strip()
    return text if text.endswith((".", "!", "?")) else text + "."


def llms_full(pages, titles, stripped, base_url):
    """Concatenate every page (as plain Markdown) into the ``llms-full.txt`` body."""
    base = base_url.rstrip("/")
    parts = ["# empyrean documentation"]
    for docname in pages:
        title = titles.get(docname, docname)
        body = stripped.get(docname, "").strip("\n")
        parts.append("# " + title + "\nSource: " + base + "/" + docname + ".md\n\n" + body)
    return "\n\n---\n\n".join(parts) + "\n"


def write_llms(outdir, docs_dir, module, base_url, version, description):
    """Write ``llms.txt``, ``llms-full.txt`` and a ``.md`` per page into ``outdir``.

    The ``api`` page is written as the generated API index; every other page is
    written as its role-stripped plain Markdown. Returns the written paths.
    """
    outdir = Path(outdir)
    docs_dir = Path(docs_dir)
    pages = page_order(docs_dir)
    titles = _titles(docs_dir)

    stripped = {}
    summaries = {}
    for docname in pages:
        if docname == "api":
            body = api_index((docs_dir / "api.md").read_text(encoding="utf-8"), module)
            stripped[docname] = body
            summaries[docname] = API_SUMMARY
        else:
            body = strip_myst((docs_dir / (docname + ".md")).read_text(encoding="utf-8"), titles)
            stripped[docname] = body
            summaries[docname] = first_sentence(body)

    written = []
    index_path = outdir / "llms.txt"
    index_path.write_text(
        llms_index(pages, titles, summaries, base_url, version, description), encoding="utf-8"
    )
    written.append(index_path)
    full_path = outdir / "llms-full.txt"
    full_path.write_text(llms_full(pages, titles, stripped, base_url), encoding="utf-8")
    written.append(full_path)
    for docname in pages:
        path = outdir / (docname + ".md")
        path.parent.mkdir(parents=True, exist_ok=True)
        body = stripped[docname]
        path.write_text(body if body.endswith("\n") else body + "\n", encoding="utf-8")
        written.append(path)
    return written


def first_sentence(text, limit=140):
    """Return the first sentence of the first prose paragraph of ``text``.

    Headings, fences, admonitions, tables, list items and target labels are
    skipped. The result is whitespace-collapsed and truncated at a word
    boundary to at most ``limit`` characters.
    """
    paragraph = _first_paragraph(text)
    if not paragraph:
        return ""
    match = re.search(r"[.!?](\s|$)", paragraph)
    sentence = paragraph[: match.start() + 1] if match else paragraph
    sentence = re.sub(r"\s+", " ", sentence).strip()
    if len(sentence) > limit:
        clipped = sentence[: limit - 1]
        if " " in clipped:
            clipped = clipped[: clipped.rfind(" ")]
        sentence = clipped.rstrip() + "…"
    return sentence


def setup(app):
    """Register the agentdocs Sphinx extension (config values + build hook)."""
    import sphinx  # noqa: F401  (import sphinx only inside setup/hook)

    app.add_config_value("agentdocs_base_url", "https://docs.empyrean-dynamics.com", "html")
    app.add_config_value("agentdocs_skill_dir", None, "html")
    app.connect("build-finished", _on_build_finished)
    return {"version": "0.1", "parallel_read_safe": True, "parallel_write_safe": True}


def main(argv):
    """Run the generators from the command line (``--skill`` and/or ``--llms``)."""
    parser = argparse.ArgumentParser(
        description="Generate the agent-facing empyrean docs (skill + llms.txt)."
    )
    parser.add_argument(
        "--skill",
        action="store_true",
        help="regenerate plugins/empyrean/skills/empyrean from the docs",
    )
    parser.add_argument(
        "--llms", metavar="OUTDIR", help="write llms.txt, llms-full.txt and page .md into OUTDIR"
    )
    parser.add_argument(
        "--base-url",
        default="https://docs.empyrean-dynamics.com",
        help="base URL used in generated links",
    )
    args = parser.parse_args(argv)

    import importlib

    module = importlib.import_module("empyrean")
    repo_root = Path(__file__).resolve().parents[3]
    docs_dir = repo_root / "empyrean-py" / "docs"

    ran = False
    if args.skill:
        skill_text = (repo_root.joinpath(*SKILL_SUBDIR) / "SKILL.md").read_text(encoding="utf-8")
        check_skill_head(skill_text, module)
        for path in write_skill(repo_root, module):
            print("wrote", path)
        ran = True
    if args.llms:
        version, description = _meta(docs_dir)
        for path in write_llms(args.llms, docs_dir, module, args.base_url, version, description):
            print("wrote", path)
        ran = True
    if not ran:
        parser.print_help()


